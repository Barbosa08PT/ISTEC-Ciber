menu = input("1.Criar   2.Atualizar   3.Eliminar   4.Sair ")

if menu == "Criar":
    print("Escolheu Criar")
else:
    if menu == "Atualizar":
        print("Escolheu Atualizar")
    else:
        if menu == "Eliminar":
            print("Escolheu Eliminar")
        else:
            if menu == "Sair":
                print("Escolheu Sair")
            else:
                print("Opcao Invalida")

